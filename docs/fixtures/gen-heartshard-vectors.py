"""Generates HeartShard-format cross-validation vectors using python-cryptography (OpenSSL)
and argon2-cffi — fully independent implementations from the Rust core.

HeartShard chunk format (docs/mixfile-study.md §2.2, rulings Q2):
  key  = blob_key (per-blob, HKDF-derived; raw 32B pinned here)
  AAD  = blob_hash(32B raw) || chunk_index(u32 BE) || total_chunks(u32 BE)
  out  = iv(12B) || ciphertext || tag(12B, 96-bit)

KDF chain:
  MK            = Argon2id(password, salt, m=64MiB, t=3, p=4, 32B)
  prk           = HKDF-Extract(salt=master_salt, ikm=MK)
  manifest_key  = HKDF-Expand(prk, info="heartshard/manifest/v1", 32B)
  config_key    = HKDF-Expand(prk, info="heartshard/config/v1", 32B)
  blob_key      = HKDF-Expand(prk, info="heartshard/blob/v1" || blob_hash(32B raw), 32B)
"""
import hashlib, json, sys
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from argon2.low_level import hash_secret_raw, Type
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes

def enc(key: bytes, iv: bytes, pt: bytes, aad: bytes) -> bytes:
    full = AESGCM(key).encrypt(iv, pt, aad)  # ct || tag(16B)
    return iv + full[: len(pt)] + full[len(pt): len(pt) + 12]  # 96-bit tag = first 12B of GCM tag

# ---- KDF case K1 ----
password = b"correct horse battery staple"
argon_salt = b"0123456789abcdef"  # 16B
mk = hash_secret_raw(secret=password, salt=argon_salt, time_cost=3, memory_cost=65536,
                     parallelism=4, hash_len=32, type=Type.ID)
master_salt = b"heartshard-master-salt-v1"

def expand(info: bytes) -> bytes:
    hk = HKDF(algorithm=hashes.SHA256(), length=32, salt=master_salt, info=info)
    # HKDF in cryptography lib does extract+expand in one step with given salt/ikm;
    # we pass ikm via derive()
    return hk

# cryptography's HKDF interface: HKDF(salt, length, info).derive(key_material)
manifest_key = HKDF(algorithm=hashes.SHA256(), length=32, salt=master_salt,
                    info=b"heartshard/manifest/v1").derive(mk)
config_key = HKDF(algorithm=hashes.SHA256(), length=32, salt=master_salt,
                  info=b"heartshard/config/v1").derive(mk)
index_key = HKDF(algorithm=hashes.SHA256(), length=32, salt=master_salt,
                 info=b"heartshard/index/v1").derive(mk)

blob_hash = hashlib.sha256(b"HeartShard M0 blob").digest()  # raw 32B
blob_key = HKDF(algorithm=hashes.SHA256(), length=32, salt=master_salt,
                info=b"heartshard/blob/v1" + blob_hash).derive(mk)

# ---- chunk case H1/H2: same blob_key, distinct fixed IVs, AAD bound to blob/index/total ----
blob_key_fixed = bytes(range(0x20, 0x40))  # pinned key for chunk vectors (independent of K1)
pt1 = b"HeartShard chunk AAD vector 01: blob_hash||index||total binding."
pt2 = b"HeartShard chunk AAD vector 02, chunk_index=2 tail chunk."
iv1 = bytes.fromhex("d0d1d2d3d4d5d6d7d8d9dadb")
iv2 = bytes.fromhex("e0e1e2e3e4e5e6e7e8e9eaeb")
ct1 = enc(blob_key_fixed, iv1, pt1, blob_hash + (0).to_bytes(4, "big") + (3).to_bytes(4, "big"))
ct2 = enc(blob_key_fixed, iv2, pt2, blob_hash + (2).to_bytes(4, "big") + (3).to_bytes(4, "big"))

out = {
    "comment": "HeartShard crypto cross-validation vectors, generated by python-cryptography (OpenSSL) + argon2-cffi. Rust core must reproduce byte-for-byte. Generated: M0 (2026-11-01).",
    "kdf": {
        "id": "K1",
        "password_utf8": password.decode(),
        "argon2_salt_hex": argon_salt.hex(),
        "argon2": {"m_cost_kib": 65536, "t_cost": 3, "parallelism": 4, "output_len": 32, "type": "argon2id", "version": 19},
        "master_salt_utf8": master_salt.decode(),
        "master_key_hex": mk.hex(),
        "manifest_key_hex": manifest_key.hex(),
        "config_key_hex": config_key.hex(),
        "index_key_hex": index_key.hex(),
        "blob_hash_hex": blob_hash.hex(),
        "blob_key_hex": blob_key.hex(),
        "blob_info": "HKDF-Expand(prk, info='heartshard/blob/v1' || blob_hash_raw32)"
    },
    "chunk": [
        {
            "id": "H1",
            "blob_key_hex": blob_key_fixed.hex(),
            "blob_hash_hex": blob_hash.hex(),
            "chunk_index": 0,
            "total_chunks": 3,
            "iv_hex": iv1.hex(),
            "plaintext_utf8": pt1.decode(),
            "ciphertext_hex": ct1.hex(),
            "ciphertext_len": len(ct1)
        },
        {
            "id": "H2",
            "blob_key_hex": blob_key_fixed.hex(),
            "blob_hash_hex": blob_hash.hex(),
            "chunk_index": 2,
            "total_chunks": 3,
            "iv_hex": iv2.hex(),
            "plaintext_utf8": pt2.decode(),
            "ciphertext_hex": ct2.hex(),
            "ciphertext_len": len(ct2)
        }
    ]
}

path = "heartshard-vectors.json"
with open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, indent=2, ensure_ascii=False)
print("wrote", path)
print("mk =", mk.hex())
print("manifest_key =", manifest_key.hex())
print("config_key =", config_key.hex())
print("blob_key =", blob_key.hex())
print("ct1 =", ct1.hex())
print("ct2 =", ct2.hex())
